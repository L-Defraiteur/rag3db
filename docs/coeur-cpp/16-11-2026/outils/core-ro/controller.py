"""Read an existing core; never execute its inferior or load a service."""
import hashlib
import json
import os
from pathlib import Path
import sys
import time

import processes as proc
from receipt import gdb_command

scratch, out = map(Path, sys.argv[1:3])
jobs, deadline = int(sys.argv[3]), float(sys.argv[4])
recipe = json.loads((out / 'recipe.json').read_text())
raw = out / 'raw'
(raw / 'parsing').mkdir(parents=True, exist_ok=True)
phase = 'preflight'
started = time.monotonic()


def write(path, value):
    path.write_text(json.dumps(value, indent=2) + '\n')


def sha(path):
    digest = hashlib.sha256()
    with path.open('rb') as stream:
        while True:
            if time.monotonic() >= deadline - 3:
                raise TimeoutError('core analysis hash deadline')
            block = stream.read(1024 * 1024)
            if not block:
                return digest.hexdigest()
            digest.update(block)


def run(argv, label, cap, env):
    return proc.run(argv, label, cap, env=env)


try:
    assert 1 <= jobs <= 8 and not any(scratch.iterdir())
    cg = next(x.split(':', 2)[2] for x in Path('/proc/self/cgroup').read_text().splitlines()
              if x.startswith('0::'))
    proc.cgp = Path('/sys/fs/cgroup') / cg.lstrip('/')
    proc.raw, proc.deadline = raw, deadline
    q, p = (proc.cgp / 'cpu.max').read_text().split()
    admission = json.loads((raw / 'driver/admission.json').read_text())
    assert q != 'max' and jobs <= int(q) // int(p) and jobs <= int(admission['poste_threads'])
    assert int(q) / int(p) <= admission['child_cpu_quota_percent'] / 100 + .00001
    limits = {'memory.max': (proc.cgp / 'memory.max').read_text().strip(),
              'memory.swap.max': (proc.cgp / 'memory.swap.max').read_text().strip(),
              'cpu.max': (proc.cgp / 'cpu.max').read_text().strip(),
              'scratch_bytes': os.statvfs(scratch).f_blocks * os.statvfs(scratch).f_frsize,
              'routes': Path('/proc/net/route').read_text()}
    write(raw / 'driver/limits.json', limits)
    assert limits['memory.max'] == '4294967296' and limits['memory.swap.max'] == '0'
    assert limits['scratch_bytes'] == 34359738368 and len(limits['routes'].splitlines()) == 1
    inputs = {item['name']: Path(item['path']) for item in recipe['inputs']}
    for item in recipe['inputs']:
        path = Path(item['path'])
        assert path.stat().st_size == item['bytes'] and sha(path) == item['sha256'], item['name']
    marker = 'rag3db-build-' + recipe['engine'] + recipe['engine_profile']
    assert marker in inputs['build_id_header'].read_text()
    assert marker.encode() in inputs['elf'].read_bytes()
    core, home, tmp, sysroot = [scratch / name for name in ['core', 'home', 'tmp', 'empty-sysroot']]
    for path in [home, tmp, sysroot]:
        path.mkdir()
    env = {'PATH': '/usr/bin:/bin', 'HOME': str(home), 'TMPDIR': str(tmp), 'LC_ALL': 'C',
           'LANG': 'C', 'TZ': 'UTC', 'DEBUGINFOD_URLS': '', 'PYTHONNOUSERSITE': '1',
           'OMP_NUM_THREADS': '1', 'OPENBLAS_NUM_THREADS': '1'}
    write(raw / 'driver/effective-env.json', env)
    # Core and all host inputs remain read-only to GDB; only private output/tmp/home are writable.
    phase = 'decompress'
    run([str(inputs['zstd']), '--decompress', '--sparse', '--no-progress',
         '-o', str(core), str(inputs['compressed_core'])], phase, 20, env)
    assert core.stat().st_size == recipe['raw_core_bytes']
    core_sha = sha(core)
    write(raw / 'parsing/decompressed-core.json', {'bytes': core.stat().st_size, 'sha256': core_sha})
    assert core_sha == recipe['raw_core_sha256']
    phase = 'gdb'
    argv = gdb_command(inputs['gdb'], inputs['elf'], core, sysroot)
    write(raw / 'parsing/gdb-command.json', argv)
    command = ['bwrap', '--unshare-user', '--unshare-net', '--ro-bind', '/', '/',
               '--proc', '/proc', '--dev', '/dev', '--ro-bind', str(core), str(core),
               '--bind', str(home), str(home), '--bind', str(tmp), str(tmp),
               '--bind', str(out), str(out), '--chdir', str(tmp),
               '/usr/bin/env', '-i', *[k + '=' + v for k, v in env.items()], *argv]
    run(command, phase, 35, env)
    # Both stdout and stderr were closed and preserved by run before this validation.
    stdout = (raw / 'gdb/stdout.log').read_text(errors='replace')
    assert 'Core was generated by' in stdout and '#0' in stdout, 'no core backtrace produced'
    assert 'Program received signal' not in stdout, 'unexpected live execution wording'
    for item in recipe['inputs']:
        assert sha(Path(item['path'])) == item['sha256']
    write(raw / 'parsing/receipt.json', {'core_sha256': core_sha, 'gdb_code': 0,
        'inferior_started': False, 'source': recipe['source'], 'engine': recipe['engine'],
        'scope': 'existing core offline metadata and bounded backtraces only',
        'debug_info_present': False, 'shared_library_symbols_auto_loaded': False,
        'causality_established': False, 'started_monotonic': started})
except BaseException as exc:
    proc.finish_child()
    write(raw / 'parsing/first-failure.json', {'phase': phase, 'type': type(exc).__name__,
        'message': str(exc), 'elapsed_s': time.monotonic() - started, 'retry': False})
    raise
